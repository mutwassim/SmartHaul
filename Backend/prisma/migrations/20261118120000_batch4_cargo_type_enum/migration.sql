-- Batch 4: cargoType becomes an enum so compatibility is an exact match (C-13)
CREATE TYPE "CargoType" AS ENUM ('GENERAL_GOODS', 'CONSTRUCTION_MATERIAL', 'AGRICULTURAL_PRODUCE', 'PACKAGED_GOODS', 'FURNITURE', 'BULK_GOODS', 'MACHINERY', 'INDUSTRIAL_RAW_MATERIAL', 'CONTAINERS', 'OVERSIZED_AND_INDUSTRIAL_CARGO', 'CONTAINERISED_GOODS', 'EXPORT_AND_IMPORT_CONSIGNMENTS', 'PERISHABLE_GOODS', 'PHARMACEUTICAL_GOODS', 'TEMPERATURE_CONTROLLED_CARGO', 'LIQUIDS_AND_BULK_FLUID', 'LOOSE_BULK_SAND_GRAVEL_EARTH');

-- Existing free-text values that already equal a category (ignoring case and spaces) are kept; anything else becomes GENERAL_GOODS
ALTER TABLE "Shipment" ALTER COLUMN "cargoType" TYPE "CargoType" USING (
  CASE
    WHEN upper(regexp_replace("cargoType", '\s+', '_', 'g')) IN (
  'GENERAL_GOODS',
  'CONSTRUCTION_MATERIAL',
  'AGRICULTURAL_PRODUCE',
  'PACKAGED_GOODS',
  'FURNITURE',
  'BULK_GOODS',
  'MACHINERY',
  'INDUSTRIAL_RAW_MATERIAL',
  'CONTAINERS',
  'OVERSIZED_AND_INDUSTRIAL_CARGO',
  'CONTAINERISED_GOODS',
  'EXPORT_AND_IMPORT_CONSIGNMENTS',
  'PERISHABLE_GOODS',
  'PHARMACEUTICAL_GOODS',
  'TEMPERATURE_CONTROLLED_CARGO',
  'LIQUIDS_AND_BULK_FLUID',
  'LOOSE_BULK_SAND_GRAVEL_EARTH'
    ) THEN upper(regexp_replace("cargoType", '\s+', '_', 'g'))::"CargoType"
    ELSE 'GENERAL_GOODS'::"CargoType"
  END
);
